export function getCategoryStyles(colorStr) {
  if (!colorStr) return { classes: "bg-slate-100 text-slate-600", dotHex: "#94a3b8", bg: "bg-slate-100", text: "text-slate-600", border: "" };

  // If it's a direct color name mapping
  if (COLORS[colorStr]) {
    const c = COLORS[colorStr];
    return {
      classes: `${c.bg} ${c.text} ${c.border || ''}`,
      dotHex: c.dotHex,
      bg: c.bg,
      text: c.text,
      border: c.border || ''
    };
  }

  // Fallback for legacy tailwind class strings (e.g. "bg-[#f3e8ff] text-[#9333ea]")
  const match = colorStr.match(/text-\[([^\]]+)\]/);
  const dotHex = match ? match[1] : "#94a3b8";
  return {
    classes: colorStr,
    dotHex: dotHex,
    bg: colorStr.split(' ').find(c => c.startsWith('bg-')) || 'bg-slate-100',
    text: colorStr.split(' ').find(c => c.startsWith('text-')) || 'text-slate-600',
    border: colorStr.split(' ').find(c => c.startsWith('border-')) || ''
  };
}

export function getCategoryIconHTML(iconStr) {
  if (!iconStr) return '<span class="text-base">●</span>';

  // If it's a known identifier
  if (ICONS[iconStr]) {
    return `<svg fill="none" viewBox="0 0 24 24" stroke="currentColor">${ICONS[iconStr]}</svg>`;
  }

  // Fallback for legacy raw SVG strings
  if (iconStr.includes("<svg")) {
    return iconStr;
  }

  return '<span class="text-base">●</span>';
}

export function reverseMapColor(bgClass) {
  if (!bgClass) return "Purple";
  for (const [colorName, data] of Object.entries(COLORS)) {
    if (data.bg === bgClass) return colorName;
  }
  return "Purple"; // fallback
}

export function reverseMapIcon(svgStr) {
  if (!svgStr) return "Store";
  for (const [iconName, pathData] of Object.entries(ICONS)) {
    if (svgStr.includes(pathData)) return iconName;
  }
  return "Store"; // fallback
}
